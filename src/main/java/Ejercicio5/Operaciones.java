package ejercicio5;

public class Operaciones {

    public static double operacion1(double suma, double x) {
        return suma + x;
    }

    public static double operacion2(double x, double y) {
        return x + Math.pow(y, 2);
    }

    public static double operacion3(double suma, double x, double y) {
        return suma + (x / y);
    }
}